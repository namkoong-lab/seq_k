from dataclasses import asdict
from datetime import datetime, timezone

from core import pricing

# UTC iso-ish, filesystem-safe (": " → "-")
_ISO_UTC = "%Y-%m-%dT%H-%M-%SZ"


# --------------------------------------------------------------------------- #
# Path construction
# --------------------------------------------------------------------------- #
# WHAT the agent gets on a retry. Content only; the WORDING is `prompt_variant`.
#   na       pass@k: independent attempts, no history
#   full     verbatim prior attempts and their feedback
#   summary  the agent's own summaries in place of the verbatim text
CONTEXT_MODES = ("na", "full", "summary")


def context_from_legacy(metric, summarize, _attempt_note=None):
    """Canonical `context` from the older `summarize` flag."""
    if metric == "pass@k":
        return "na"
    return "summary" if summarize else "full"


def summarizes(context):
    """Whether this context replaces verbatim history with self-summaries."""
    if context in (None, "na"):
        return False
    if context not in CONTEXT_MODES:
        raise ValueError(f"context must be one of {CONTEXT_MODES}, got {context!r}")
    return context == "summary"


def build_run_path(*, runs_root, benchmark_module, options, metric, k, model, judge_model,
                   critic_model, feedback_mode, context, prompt_variant="v1",
                   temperature=0.7, seed=None, reasoning_effort=None):
    """Compose the run's human-readable LABEL (not its storage location).

    Storage is content-addressed by fingerprint now; this string is what appears
    under `runs/by-label/`, in the manifest's `label_path`, and in the migration
    tools. Pass `runs_root=""` for the bare relative label.

    Every level is LABELLED and always present:

        <slice>/metric=<m>/k=<KK>/agent=<M>/judge=<M|harbor|deterministic>/
        fb=<mode>[@<critic>]/context=<spec>/prompt=<id>/temp=<t>/seed=<n|na>[,reason=<lvl>]

    Design notes:
      * Labels, not positions. `agent=` is the model under test, `judge=` grades
        it, and the critic (which writes feedback) rides on `fb=`. Three model
        fields, three names, never confusable.
      * `fb=` keeps the MODE even when an LLM critic is used: clbench has two
        LLM-critic modes (socratic, directive), so `fb=<critic-model>` alone
        would silently merge two different experiments into one directory.
      * `k` is its own level because it is an INPUT TO THE PROMPT, not just an
        attempt count ("This is attempt 1 of 5" vs "of 10"), and it cannot be
        recovered from the files — seq@k stops early on success, so a 3-attempt
        task could be k=5 or k=10.
      * Zero-padded k so k=05 sorts before k=10.
      * `reason=` only appears when reasoning_effort is set (one benchmark uses
        it); everything else is always emitted so depth is uniform and
        `runs/*/*/*/*/*/*/*/*/*/*/` matches every run.
    """
    mod = importlib.import_module(benchmark_module) if isinstance(benchmark_module, str) else benchmark_module
    if context not in CONTEXT_MODES:
        raise ValueError(f"context must be one of {CONTEXT_MODES}, got {context!r}")
    # Resolve the two module-dependent fields, then hand off to the pure
    # formatter so there is exactly ONE implementation of the label.
    return os.path.join(runs_root, label_from_fields(
        slice_key=mod.slice_name(options or {}), metric=metric, k=k, model=model,
        judge_model=(judge_model if mod.VERIFIER == "llm" else mod.VERIFIER),
        critic_model=(critic_model if feedback_mode in getattr(mod, "LLM_CRITIC_MODES", set())
                      else None),
        feedback_mode=feedback_mode, context=context, prompt_variant=prompt_variant,
        temperature=temperature, seed=seed, reasoning_effort=reasoning_effort))


def label_from_fields(*, slice_key, metric, k, model, judge_model, critic_model,
                      feedback_mode, context, prompt_variant="v1", temperature=0.7,
                      seed=None, reasoning_effort=None):
    """The readable label, from ALREADY-RESOLVED values.

    Takes exactly the columns stored in `runs`, so a label can be regenerated
    from the database without importing the benchmark. `judge_model` is expected
    to be the resolved grader ('harbor'/'deterministic' for non-LLM verifiers)
    and `critic_model` None unless the feedback mode uses one — which is how
    both the identity and the DB record them.

    This is why `label_path` is NOT a stored column: it is a pure function of
    fields we already keep, and caching it would let it drift (a horizon-free
    run extended from k=5 to k=10 would keep the stale k=05 label).
    """
    # Empty, not a sentinel: a pass@k run has no feedback channel and no retry
    # context, and `fb=`/`context=` says that more honestly than `fb=na`. The
    # segment is still emitted so the path keeps a uniform depth.
    fb = '' if feedback_mode is None else str(feedback_mode)
    if critic_model:
        fb = f"{fb}@{_safe(critic_model)}"
    last = f"seed={'na' if seed is None else int(seed)}"
    if reasoning_effort is not None:
        last += f",reason={reasoning_effort}"
    return "/".join([
        slice_key,
        f"metric={_metric_short(metric)}",
        f"k={int(k):02d}",
        f"agent={_safe(model)}",
        f"judge={_safe(judge_model)}",
        f"fb={fb}",
        f"context={context or ''}",
        f"prompt={prompt_variant}",
        f"temp={temperature}",
        last,
    ])


def task_dir(run_path, canonical_index):
    return os.path.join(run_path, f"task-{canonical_index}")


def attempt_file(run_path, canonical_index, attempt_index):
    return os.path.join(task_dir(run_path, canonical_index), f"attempt-{attempt_index}.json")


