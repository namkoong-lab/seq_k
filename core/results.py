def print_step(step, limit=3000):
    print(_render_step(asdict(step), limit))


def cumulative_best_by_attempt(traj, k):
    best, curve = 0.0, []
    steps = traj["steps"]
    for t in range(k):
        if t < len(steps):
            best = max(best, steps[t]["judge"]["score"])
        curve.append(best)
    return curve


