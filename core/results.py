_TASK_DIR = re.compile(r"^task-(?P<idx>\d+)$")
_ATTEMPT_FILE = re.compile(r"^attempt-(?P<idx>\d+)\.json$")


def _metric_short(metric):
    return {"pass@k": "passk", "seq@k": "seqk"}.get(metric, metric.replace("@", ""))


def _safe(name):
    """Make a model id filesystem-safe: '/' → '__'. Round-trippable."""
    return str(name).replace("/", "__")


def _now():
    return datetime.now(timezone.utc).strftime(_ISO_UTC)


def _load_task_attempts(run_path, canonical_index):
    d = task_dir(run_path, canonical_index)
    if not os.path.isdir(d):
        return []
    attempts = []
    for name in os.listdir(d):
        m = _ATTEMPT_FILE.match(name)
        if not m:
            continue
        with open(os.path.join(d, name), encoding="utf-8") as f:
            attempts.append(json.load(f))
    return sorted(attempts, key=lambda a: a["attempt_index"])


def _refresh_task_summary(run_path, canonical_index, *, task_id):
    """Rewrite task-<i>/summary.json from current attempt files. Includes
    per-model token totals (input / cached / output) summed across every LLM
    call in every attempt of this task."""
    attempts = _load_task_attempts(run_path, canonical_index)
    if not attempts:
        return
    summary = {
        "task_id": task_id,
        "task_index": canonical_index,
        "success": any(a["judge"]["success"] for a in attempts),
        "best_score": max(a["judge"]["score"] for a in attempts),
        "last_updated": _now(),
        "attempts": [
            {"attempt": a["attempt_index"], "success": a["judge"]["success"], "score": a["judge"]["score"]}
            for a in attempts
        ],
        "tokens": _tokens_across_attempts(attempts),
        "pricing_last_updated": pricing.PRICING_LAST_UPDATED,
        "litellm_version": pricing.litellm_version(),
    }
    _write(os.path.join(task_dir(run_path, canonical_index), "summary.json"), _json(summary))


def _tokens_across_attempts(attempts):
    """Aggregate token usage across attempts, keyed by model id.

    Combines actor (one count per attempt) + each judge call + each critic call
    + each summarizer call. Same model used by multiple roles → merged into one
    entry. Each entry gets a derived `cost_usd` from core/pricing.py (null if
    model not in table).

    NOTE on summarizer tokens: they are deliberately EXCLUDED from output_budget
    accounting (see harness._round_actor_output_tokens) but INCLUDED here — the
    budget measures answer effort, cost accounting measures money spent."""
    by_model = {}
    for a in attempts:
        actor = a["actor"]
        _add(by_model, actor["model"], actor)
        for call in a["judge"].get("calls") or []:
            _add(by_model, call["model"], call)
        for call in a["critic"].get("calls") or []:
            _add(by_model, call["model"], call)
        for call in (a.get("summarizer") or {}).get("calls") or []:
            _add(by_model, call["model"], call)
    _annotate_costs(by_model)
    return by_model


def _annotate_costs(by_model):
    """In-place: attach `cost_usd` + `cost_source` to each entry, and drop the
    private accumulators _add left behind.

    Provider-reported cost is used only when EVERY call in the bucket reported
    one. A bucket where some calls reported and some didn't (mixed providers, or
    an agentic actor whose tokens came from Harbor rather than a response body)
    would sum to a silent undercount, so those fall back to rate-table math on
    the full token counts instead.
    """
    for model, bucket in by_model.items():
        n, n_reported = bucket.pop("_calls", 0), bucket.pop("_calls_with_cost", 0)
        reported = bucket.pop("_reported_cost", 0.0)
        reported = reported if (n and n == n_reported) else None
        bucket["cost_usd"], bucket["cost_source"] = pricing.cost_for(
            model, bucket["input_tokens"], bucket["cached_tokens"], bucket["output_tokens"],
            reported_cost=reported,
        )


_TOKEN_FIELDS = ("input_tokens", "cached_tokens", "thinking_tokens", "output_tokens")


def _add(by_model, model, src):
    """Sum the four token fields from `src` into the per-model bucket, and track
    any provider-reported cost alongside them.

    OpenRouter returns `usage.cost` (what it actually charged) on every response;
    we persist the whole response, so it's readable straight back out of the saved
    attempt. Providers that don't report one just leave _calls_with_cost short of
    _calls, which makes _annotate_costs fall back to rate tables."""
    bucket = by_model.setdefault(model, {k: 0 for k in _TOKEN_FIELDS})
    for k in _TOKEN_FIELDS:
        # `or 0`, not `.get(k, 0)`: the default only fires when the key is ABSENT.
        # Imported attempts carry these keys with an explicit null (upstream logged
        # no token counts), and int(None) raises — which crashed save_summary on
        # every run whose attempts came from an import.
        bucket[k] += int(src.get(k) or 0)
    bucket["_calls"] = bucket.get("_calls", 0) + 1
    cost = _reported_cost(src)
    if cost is not None:
        bucket["_calls_with_cost"] = bucket.get("_calls_with_cost", 0) + 1
        bucket["_reported_cost"] = bucket.get("_reported_cost", 0.0) + cost


def _reported_cost(src):
    """The provider's own charge for one call, from the stored raw_response.
    None when absent — pre-raw_response attempt files, agentic actor sections,
    and providers that simply don't report cost all land here."""
    usage = ((src.get("raw_response") or {}).get("usage") or {})
    cost = usage.get("cost")
    try:
        return float(cost) if cost is not None else None
    except (TypeError, ValueError):
        return None


def _assemble(attempts):
    attempts = sorted(attempts, key=lambda a: a["attempt_index"])
    first = attempts[0]
    steps = []
    for a in attempts:
        step = {
            "attempt_index": a["attempt_index"],
            "actor": a["actor"],
            "judge": a["judge"],
            "critic": a["critic"],
        }
        # Only present on summarize-on runs; keep it absent otherwise so the
        # reconstructed view matches the saved file shape.
        if a.get("summarizer") is not None:
            step["summarizer"] = a["summarizer"]
        steps.append(step)
    return {
        "task_id": first["task_id"],
        "task_index": first["task_index"],
        "metric": first["metric"],
        "feedback_mode": first["feedback_mode"],
        "model": first["actor"]["model"],
        "steps": steps,
        "success": any(s["judge"]["success"] for s in steps),
        "best_score": max(s["judge"]["score"] for s in steps),
    }


def _summary_view(trajs, k):
    if not trajs:
        return {"tasks": 0, "k": k}
    metric = trajs[0]["metric"]
    label = "seq" if metric == "seq@k" else "pass"
    curves = [cumulative_best_by_attempt(t, k) for t in trajs]
    at = [sum(c[t] for c in curves) / len(curves) for t in range(k)]
    summary = {
        "metric": metric,
        "model": trajs[0]["model"],
        "feedback_mode": trajs[0]["feedback_mode"],
        "tasks": len(trajs),
        "k": k,
    }
    for t in range(k):
        summary[f"{label}@{t + 1}"] = round(at[t], 4)
    # Standard error of the mean for {pass,seq}@1 .. @k, treating tasks as the
    # sampling unit. Formula: SE = sqrt(sample_variance / n_tasks) where
    # sample_variance uses Bessel's correction (n-1 divisor). Reduces to the
    # Wald binomial SE sqrt(p(1-p)/n) for binary judge scores (a side-effect of
    # the algebra, not a separate code path) and gives the right SE on
    # continuous judge scores (rubrics, partial credit) too.
    n = len(curves)
    se_curve = []
    for t in range(k):
        if n > 1:
            vals = [c[t] for c in curves]
            var = sum((v - at[t]) ** 2 for v in vals) / (n - 1)
            se_curve.append((var / n) ** 0.5)
        else:
            se_curve.append(0.0)
    summary["se"] = {f"{label}@{t + 1}": round(se_curve[t], 4) for t in range(k)}
    if metric == "seq@k" and k >= 2:
        delta = at[k - 1] - at[0]
        summary["delta"] = round(delta, 4)
        if delta > 0:
            summary["EGS"] = round((at[1] - at[0]) / delta, 3)
            summary["LGS"] = round((at[k - 1] - at[k - 2]) / delta, 3)
    # Tokens summed across every attempt of every task, grouped by model.
    by_model = {}
    for t in trajs:
        for step in t["steps"]:
            _add(by_model, step["actor"]["model"], step["actor"])
            for c in step["judge"].get("calls") or []:
                _add(by_model, c["model"], c)
            for c in step["critic"].get("calls") or []:
                _add(by_model, c["model"], c)
            for c in (step.get("summarizer") or {}).get("calls") or []:
                _add(by_model, c["model"], c)
    _annotate_costs(by_model)
    summary["tokens"] = by_model
    summary["pricing_last_updated"] = pricing.PRICING_LAST_UPDATED
    # Recorded because a "litellm"-sourced cost_usd moves when litellm is upgraded;
    # "table" and "reported" costs are reproducible without it.
    summary["litellm_version"] = pricing.litellm_version()
    return summary


def _json(obj):
    return json.dumps(obj, ensure_ascii=False, indent=2) + "\n"


def _write(path, text):
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(text)
    os.replace(tmp, path)


def _truncate(text, limit):
    text = "" if text is None else str(text)
    if limit and len(text) > limit:
        return text[:limit] + f"\n…[truncated {len(text) - limit} chars; full text in results folder]"
    return text


def _render_step(step, limit):
    j = step["judge"]
    c = step["critic"]
    status = j["details"].get("requirement_status")
    verdict = "PASS" if j["success"] else "FAIL"
    lines = [
        f"\n--- attempt {step['attempt_index']} ---",
        f"ACTOR ({step['actor']['model']}) PROMPT (what the model saw):",
        _truncate(step["actor"]["prompt"], limit),
        "\nACTOR OUTPUT:",
        _truncate(step["actor"]["output"], limit),
        f"\nJUDGE ({j['model']}) VERDICT: {verdict}  score={j['score']}",
    ]
    if status:
        lines.append(f"rubrics: {status}")
    for i, call in enumerate(j["calls"], 1):
        lines.append(f"\nJUDGE CALL {i} ({call['model']}):")
        lines.append("  prompt:"); lines.append(_truncate(call["prompt"], limit))
        lines.append("  output:"); lines.append(_truncate(call["output"], limit))
    for i, call in enumerate(c["calls"], 1):
        lines.append(f"\nCRITIC CALL {i} ({call['model']}):")
        lines.append("  prompt:"); lines.append(_truncate(call["prompt"], limit))
        lines.append("  output:"); lines.append(_truncate(call["output"], limit))
    if c["feedback"]:
        lines.append(f"\nCRITIC ({c['model']}) FEEDBACK INTO NEXT ATTEMPT:")
        lines.append(_truncate(c["feedback"], limit))
    s = step.get("summarizer") or {}
    for i, call in enumerate(s.get("calls") or [], 1):
        lines.append(f"\nSUMMARIZER CALL {i} ({call['model']}):")
        lines.append("  prompt:"); lines.append(_truncate(call["prompt"], limit))
        lines.append("  output:"); lines.append(_truncate(call["output"], limit))
    if s.get("summary"):
        lines.append(f"\nSUMMARIZER ({s['model']}) SUMMARY INTO NEXT ATTEMPT "
                     f"(replaces the attempt + feedback above):")
        lines.append(_truncate(s["summary"], limit))
    return "\n".join(lines)
