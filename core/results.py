def init_run(run_path, *, continue_run=False, **config):
    """Freeze config.json inside an already-resolved run directory.

    The directory itself now comes from core.registry, keyed by the identity
    FINGERPRINT rather than by a path built from the config (see core/ids.py).
    Two configs that resolve here are identical on every result-affecting field,
    so re-running simply RESUMES — already-done tasks are skipped.

    This used to carry a guard refusing a changed `output_budget`, because that
    one field affected results but was deliberately left out of the path. It is
    part of the fingerprint now, so a different budget resolves to a different
    run and there is nothing left to police.

    config.json is kept alongside manifest.json for backward compatibility: the
    existing readers (the import tools, anything pointed at an archived run)
    all expect it, and it costs a few hundred bytes.
    """
    os.makedirs(run_path, exist_ok=True)
    _write(os.path.join(run_path, "config.json"), _json(config))


def code_provenance():
    """Git commit + library versions, recorded in the manifest so a result can
    be traced back to the code that produced it."""
    import subprocess
    info = {"litellm": pricing.litellm_version(),
            "pricing_last_updated": pricing.PRICING_LAST_UPDATED}
    repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    try:
        run = lambda *a: subprocess.run(a, cwd=repo, capture_output=True, text=True, timeout=5)
        head = run("git", "rev-parse", "--short", "HEAD")
        if head.returncode == 0:
            info["git_commit"] = head.stdout.strip()
            info["git_dirty"] = bool(run("git", "status", "--porcelain").stdout.strip())
    except (OSError, subprocess.SubprocessError):
        pass
    return info


def save_task_meta(run_path, task):
    """Write task-<i>/task_meta.json once. Skips if already present."""
    path = os.path.join(task_dir(run_path, task.canonical_index), "task_meta.json")
    if os.path.exists(path):
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    _write(path, _json({
        "task_id": task.id,
        "task_index": task.canonical_index,
        "prompt": task.prompt,
    }))


def save_attempt(*, run_path, task, step, metric, feedback_mode):
    """Write task-<i>/attempt-<j>.json AND refresh that task's per-task summary."""
    path = attempt_file(run_path, task.canonical_index, step.attempt_index)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    payload = {
        "task_id": task.id,
        "task_index": task.canonical_index,
        "metric": metric,
        "feedback_mode": feedback_mode,
        **asdict(step),
    }
    # Drop the summarizer key entirely when the run isn't summarizing, so runs
    # with the flag off keep the exact three-section schema they had before the
    # feature existed (same policy as actor.budget under output_budget).
    if payload.get("summarizer") is None:
        payload.pop("summarizer", None)
    _write(path, _json(payload))
    _refresh_task_summary(run_path, task.canonical_index, task_id=task.id)


def patch_attempt(run_path, canonical_index, attempt_index, **sections):
    """Merge whole sections into an already-written attempt file, in place.

    Narrow on purpose: it replaces top-level sections (`critic`, `summarizer`)
    and nothing else, so the actor's generation and the judge's verdict can
    never be rewritten by it. The one caller is the harness backfilling a
    critic/summary that was never recorded for an attempt a later attempt is
    about to be built on top of — see harness._backfill_retry_context.

    Returns the attempt as written, or None when there is no such file.
    """
    path = attempt_file(run_path, canonical_index, attempt_index)
    if not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as f:
        a = json.load(f)
    a.update(sections)
    _write(path, _json(a))
    _refresh_task_summary(run_path, canonical_index, task_id=a.get("task_id"))
    return a


def save_summary(run_path, k):
    """Write run-level summary.json (aggregate; per-task lives in task-*/summary.json)."""
    trajs = load(run_path)
    summary = _summary_view(trajs, k)
    summary["last_updated"] = _now()
    _write(os.path.join(run_path, "summary.json"), _json(summary))


