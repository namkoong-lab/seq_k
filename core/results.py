"""Layout: content-addressed run directories, plus a human-readable label view.

A run's directory is `runs/<benchmark>/<run_id>/`, resolved from the config's
identity FINGERPRINT by core/registry.py. Same config -> same
fingerprint -> same folder -> re-running auto-resumes, exactly as the old
derived path did, but without the path having to encode the config.

`build_run_path` below is now a LABEL FORMATTER. It still produces the v2 name,
which is used for `runs/by-label/<name> -> <uuid dir>` symlinks, for the
`label_path` field in the manifest, and by the migration tools. It no longer
decides where anything is stored.

    runs/
    ├── .registry.json            fingerprint -> storage key (rebuildable cache)
    ├── by-label/<v2 name>        symlink view, derived, gitignored
    └── <benchmark>/<run_id>/
        ├── manifest.json         identity, labels, provenance, rollup
        ├── config.json           frozen config (kept for existing readers)
        ├── summary.json          aggregate metrics
        └── task-<i>/
            ├── task_meta.json
            └── attempt-<j>.json

The label, unchanged from v2:

    <slice>/                      benchmark + dataset variant (benchmark.slice_name)
        └── metric=<passk|seqk>/
            └── k=<KK>/           zero-padded so k=05 sorts before k=10
                └── agent=<M>/    THE MODEL UNDER TEST
                    └── judge=<M|harbor|deterministic>/    the grader
                        └── fb=<mode>[@<critic-model>]/    feedback channel (+ who writes it)
                            └── context=<spec>/            retry-context treatment
                                └── prompt=<id>/           prompt-template version
                                    └── temp=<t>/
                                        └── seed=<n|na>[,reason=<lvl>]/

EVERY level is LABELLED and always present, so depth is uniform and any slice of
the grid globs cleanly, e.g. all k=10 summarised seq@k runs:

    runs/by-label/*/metric=seqk/k=10/*/*/*/context=summary/*/*/*

Why these fields and not others:
  * `agent=` / `judge=` / `fb=...@critic` — three model-valued fields, three
    distinct labels, so they can never be mistaken for one another.
  * `fb=` keeps the MODE even with an LLM critic: clbench has two LLM-critic
    modes (socratic, directive) that would otherwise share a directory.
  * `k` is an INPUT TO THE PROMPT ("attempt 1 of 5" vs "of 10"), and cannot be
    recovered from the files because seq@k stops early on success.
  * `context` folds the old summarize + attempt_note into one axis; pass@k is
    `na` because it has no history at all.
  * `prompt` exists so editing a template forces a new path instead of silently
    resuming into data generated by the previous wording.

Fields NOT in the label but IN the fingerprint (core/ids.py) — `output_budget`
and `summarizer_model`. Under v2 these were policed by a hand-written guard;
now they simply resolve to a different run, so two labels can collide in
by-label/ while the underlying runs stay correctly separate. The symlink writer
never clobbers, and the manifest is always authoritative.

Saved attempt JSON shape — IDENTICAL across every benchmark:

    {
      "task_id", "task_index", "metric", "feedback_mode", "attempt_index",
      "actor":      {model, prompt, output, tokens..., finish_reason, raw_response},
      "judge":      {model, success, score, raw_eval_output, details, calls},
      "critic":     {model, feedback, calls},
      "summarizer": {model, summary, calls}   # only when context=summary*
    }
"""

